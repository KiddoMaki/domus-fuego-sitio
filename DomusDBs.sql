-- Reemplaza las columnas eliminadas costo_total y costo_porcion
CREATE VIEW v_costo_receta AS
SELECT cr.id_costo_receta,
       cr.id_receta,
       cr.fecha_calculo,
       cr.rendimiento,
       COALESCE(SUM(d.cantidad * d.costo_unitario), 0)::NUMERIC(14,4)                  AS costo_total,
       (COALESCE(SUM(d.cantidad * d.costo_unitario), 0) / cr.rendimiento)::NUMERIC(14,4) AS costo_porcion
FROM costo_receta cr
LEFT JOIN costo_receta_detalle d USING (id_costo_receta)
GROUP BY cr.id_costo_receta;

-- Reemplaza origen_tipo de movimiento_inventario y origen de lote_inventario
CREATE VIEW v_movimiento_inventario AS
SELECT m.*,
       t.signo * m.cantidad AS cantidad_con_signo,
       CASE
           WHEN m.id_recepcion_detalle IS NOT NULL THEN 'recepcion'
           WHEN m.id_op_detalle        IS NOT NULL THEN 'consumo_produccion'
           WHEN m.id_orden_produccion  IS NOT NULL THEN 'ingreso_produccion'
           WHEN m.id_pedido_detalle    IS NOT NULL THEN 'venta'
           WHEN EXISTS (SELECT 1 FROM merma x WHERE x.id_movimiento = m.id_movimiento) THEN 'merma'
           ELSE 'ajuste'
       END AS origen
FROM movimiento_inventario m
JOIN tipo_movimiento t USING (id_tipo_movimiento);

CREATE VIEW v_lote_inventario AS
SELECT l.*,
       CASE
           WHEN l.id_recepcion_detalle IS NOT NULL THEN 'compra'
           WHEN l.id_orden_produccion  IS NOT NULL THEN 'produccion'
           ELSE 'inicial'
       END AS origen
FROM lote_inventario l;

-- Reemplaza el signo eliminado de movimiento_contable
CREATE VIEW v_movimiento_contable AS
SELECT mc.*, t.nombre AS tipo, t.signo, t.signo * mc.monto AS monto_con_signo
FROM movimiento_contable mc
JOIN tipo_movimiento_contable t USING (id_tipo_movimiento_contable);

