-- =====================================================================
-- PhysicalDataModel_4 - Esquema normalizado para PostgreSQL 13 o superior
-- Origen: PhysicalDataModel_4.pdm (PowerDesigner, destino PostgreSQL 9.x)
-- Uso:    createdb restaurante && psql -d restaurante -f PhysicalDataModel_4_postgresql.sql
--
-- Cambios respecto al modelo original (detalle en cada tabla, marcados con [N]):
--   [N1] 1FN: costo_receta.detalle_json pasa a la tabla costo_receta_detalle.
--   [N2] 3FN: movimiento_contable.signo dependía de tipo; ahora ambos viven en
--        tipo_movimiento_contable.
--   [N3] 3FN: gasto_operativo.categoria (texto repetido) pasa a categoria_gasto.
--   [N4] Asociación polimórfica movimiento_inventario.origen_tipo/origen_id
--        reemplazada por claves foráneas reales al documento de origen.
--   [N5] Atributos derivables eliminados: lote_inventario.origen,
--        costo_receta.costo_total y costo_porcion (se calculan en v_costo_receta).
--   [N6] id_usuario e id_usuario_responsable no tenían tabla: se crea usuario.
--   [N7] pedido_detalle_orden tenía UNIQUE(id_orden_produccion), es decir, era
--        una relación 1:N; pasa a orden_produccion.id_pedido_detalle.
--   [N8] Claves foráneas compuestas para que datos duplicados no se contradigan
--        (lote e ítem de un movimiento; orden de compra de una recepción).
--   SERIAL pasa a IDENTITY, se indexan todas las claves foráneas y se añaden
--   CHECK de cantidades, signos, porcentajes y fechas. Las listas de estados
--   son supuestas y están al final del script para ajustarlas fácilmente.
-- =====================================================================

BEGIN;

CREATE EXTENSION IF NOT EXISTS btree_gist;  -- Para impedir precios de venta con vigencias superpuestas

-- =====================================================================
-- 1. Catálogos
-- =====================================================================

-- [N6] Nueva: responsables de movimientos de inventario y mermas
CREATE TABLE usuario (
    id_usuario  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(120) NOT NULL,
    activo      BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE unidad_medida (
    id_unidad      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(20)   NOT NULL UNIQUE,
    simbolo        VARCHAR(10)   NOT NULL,
    factor_base    NUMERIC(14,6) NOT NULL,  -- Conversión a la unidad base de su magnitud
    tipo_magnitud  VARCHAR(10)   NOT NULL,
    CONSTRAINT chk_unidad_factor CHECK (factor_base > 0)
);

CREATE TABLE categoria_item (
    id_categoria  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(60) NOT NULL UNIQUE,
    tipo          VARCHAR(20) NOT NULL
);

CREATE TABLE proveedor (
    id_proveedor  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(120) NOT NULL,
    contacto      VARCHAR(120),
    telefono      VARCHAR(30),
    email         VARCHAR(120),
    activo        BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE tipo_movimiento (
    id_tipo_movimiento  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              VARCHAR(30) NOT NULL UNIQUE,
    signo               SMALLINT    NOT NULL,  -- 1 entrada, -1 salida, 0 sin efecto
    afecta_stock        BOOLEAN     NOT NULL,
    CONSTRAINT chk_tipo_mov_signo CHECK (signo IN (-1, 0, 1))
);

CREATE TABLE cliente (
    id_cliente  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(120) NOT NULL,
    telefono    VARCHAR(30),
    email       VARCHAR(120)
);

CREATE TABLE mesa (
    id_mesa    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero     VARCHAR(10) NOT NULL UNIQUE,
    capacidad  INTEGER     NOT NULL,
    ubicacion  VARCHAR(60),
    activa     BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_mesa_capacidad CHECK (capacidad > 0)
);

CREATE TABLE caja_sesion (
    id_caja_sesion  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_apertura  TIMESTAMP     NOT NULL DEFAULT now(),
    fecha_cierre    TIMESTAMP,
    monto_apertura  NUMERIC(12,2) NOT NULL,
    monto_cierre    NUMERIC(12,2),
    estado          VARCHAR(15)   NOT NULL DEFAULT 'abierta',
    CONSTRAINT chk_caja_montos CHECK (monto_apertura >= 0 AND (monto_cierre IS NULL OR monto_cierre >= 0)),
    CONSTRAINT chk_caja_fechas CHECK (fecha_cierre IS NULL OR fecha_cierre >= fecha_apertura),
    -- Una sesión cerrada tiene fecha y monto de cierre; una abierta todavía no
    CONSTRAINT chk_caja_cierre CHECK (
        (estado =  'cerrada' AND fecha_cierre IS NOT NULL AND monto_cierre IS NOT NULL) OR
        (estado <> 'cerrada' AND fecha_cierre IS NULL     AND monto_cierre IS NULL)
    )
);

-- [N3] Nueva: categorías de gasto, antes texto libre en gasto_operativo
CREATE TABLE categoria_gasto (
    id_categoria_gasto  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              VARCHAR(40) NOT NULL UNIQUE
);

-- [N2] Nueva: el signo depende del tipo, no de cada movimiento contable
CREATE TABLE tipo_movimiento_contable (
    id_tipo_movimiento_contable  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                       VARCHAR(20) NOT NULL UNIQUE,
    signo                        SMALLINT    NOT NULL,  -- 1 ingreso, -1 egreso
    CONSTRAINT chk_tipo_mc_signo CHECK (signo IN (-1, 1))
);

-- =====================================================================
-- 2. Ítems, presentaciones, precios y recetas
-- =====================================================================

CREATE TABLE item (
    id_item           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            VARCHAR(120)  NOT NULL,
    id_categoria      INTEGER       NOT NULL REFERENCES categoria_item (id_categoria) ON DELETE RESTRICT,
    tipo_item         VARCHAR(20)   NOT NULL,
    id_unidad_base    INTEGER       NOT NULL REFERENCES unidad_medida (id_unidad) ON DELETE RESTRICT,
    maneja_lote       BOOLEAN       NOT NULL DEFAULT FALSE,
    perecedero        BOOLEAN       NOT NULL DEFAULT FALSE,
    vida_util_dias    INTEGER,
    politica_consumo  VARCHAR(10)   NOT NULL DEFAULT 'FIFO',
    stock_minimo      NUMERIC(14,4) NOT NULL DEFAULT 0,
    activo            BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_item_stock_minimo CHECK (stock_minimo >= 0),
    -- La vida útil solo tiene sentido en ítems perecederos
    CONSTRAINT chk_item_vida_util CHECK (
        vida_util_dias IS NULL OR (perecedero AND vida_util_dias > 0)
    )
);

CREATE INDEX idx_item_categoria ON item (id_categoria);
CREATE INDEX idx_item_unidad_base ON item (id_unidad_base);

CREATE TABLE item_proveedor (
    id_item_proveedor  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_item            INTEGER       NOT NULL REFERENCES item (id_item) ON DELETE CASCADE,
    id_proveedor       INTEGER       NOT NULL REFERENCES proveedor (id_proveedor) ON DELETE CASCADE,
    codigo_proveedor   VARCHAR(60),
    precio_referencia  NUMERIC(12,4),
    CONSTRAINT uq_item_proveedor UNIQUE (id_item, id_proveedor),
    CONSTRAINT chk_item_proveedor_precio CHECK (precio_referencia IS NULL OR precio_referencia >= 0)
);

CREATE INDEX idx_item_proveedor_proveedor ON item_proveedor (id_proveedor);

CREATE TABLE item_presentacion (
    id_presentacion  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_item          INTEGER       NOT NULL REFERENCES item (id_item) ON DELETE CASCADE,
    nombre           VARCHAR(60)   NOT NULL,
    id_unidad        INTEGER       NOT NULL REFERENCES unidad_medida (id_unidad) ON DELETE RESTRICT,
    factor_unidad    NUMERIC(14,6) NOT NULL,
    es_venta         BOOLEAN       NOT NULL DEFAULT FALSE,
    es_compra        BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_item_presentacion UNIQUE (id_item, nombre),
    CONSTRAINT chk_presentacion_factor CHECK (factor_unidad > 0)
);

CREATE INDEX idx_presentacion_unidad ON item_presentacion (id_unidad);

CREATE TABLE precio_venta (
    id_precio        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_presentacion  INTEGER       NOT NULL REFERENCES item_presentacion (id_presentacion) ON DELETE CASCADE,
    precio           NUMERIC(12,2) NOT NULL,
    vigente_desde    TIMESTAMP     NOT NULL DEFAULT now(),
    vigente_hasta    TIMESTAMP,  -- NULL = vigente sin fecha de fin
    CONSTRAINT chk_precio_venta CHECK (precio >= 0),
    CONSTRAINT chk_precio_vigencia CHECK (vigente_hasta IS NULL OR vigente_hasta > vigente_desde),
    -- Una presentación no puede tener dos precios vigentes al mismo tiempo
    CONSTRAINT excl_precio_superpuesto EXCLUDE USING gist (
        id_presentacion WITH =,
        tsrange(vigente_desde, vigente_hasta) WITH &&
    )
);

CREATE TABLE receta (
    id_receta              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_item_resultante     INTEGER       NOT NULL REFERENCES item (id_item) ON DELETE RESTRICT,
    nombre                 VARCHAR(120)  NOT NULL,
    tipo                   VARCHAR(15)   NOT NULL,
    rendimiento            NUMERIC(14,4) NOT NULL,
    id_unidad_rendimiento  INTEGER       NOT NULL REFERENCES unidad_medida (id_unidad) ON DELETE RESTRICT,
    activa                 BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_receta UNIQUE (id_item_resultante, nombre),
    CONSTRAINT chk_receta_rendimiento CHECK (rendimiento > 0)
);

CREATE INDEX idx_receta_unidad ON receta (id_unidad_rendimiento);

CREATE TABLE receta_detalle (
    id_receta_detalle   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_receta           INTEGER       NOT NULL REFERENCES receta (id_receta) ON DELETE CASCADE,
    id_item_insumo      INTEGER       NOT NULL REFERENCES item (id_item) ON DELETE RESTRICT,
    cantidad            NUMERIC(14,4) NOT NULL,
    id_unidad           INTEGER       NOT NULL REFERENCES unidad_medida (id_unidad) ON DELETE RESTRICT,
    merma_esperada_pct  NUMERIC(5,2)  NOT NULL DEFAULT 0,
    CONSTRAINT uq_receta_detalle UNIQUE (id_receta, id_item_insumo),
    CONSTRAINT chk_receta_detalle_cantidad CHECK (cantidad > 0),
    CONSTRAINT chk_receta_detalle_merma CHECK (merma_esperada_pct >= 0 AND merma_esperada_pct < 100)
);

CREATE INDEX idx_receta_detalle_insumo ON receta_detalle (id_item_insumo);
CREATE INDEX idx_receta_detalle_unidad ON receta_detalle (id_unidad);

-- =====================================================================
-- 3. Compras y recepción
-- =====================================================================

CREATE TABLE orden_compra (
    id_orden_compra  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proveedor     INTEGER     NOT NULL REFERENCES proveedor (id_proveedor) ON DELETE RESTRICT,
    fecha_emision    TIMESTAMP   NOT NULL DEFAULT now(),
    estado           VARCHAR(20) NOT NULL DEFAULT 'borrador',
    observaciones    TEXT
);

CREATE INDEX idx_orden_compra_proveedor ON orden_compra (id_proveedor);

CREATE TABLE orden_compra_detalle (
    id_oc_detalle        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden_compra      INTEGER       NOT NULL REFERENCES orden_compra (id_orden_compra) ON DELETE CASCADE,
    id_item              INTEGER       NOT NULL REFERENCES item (id_item) ON DELETE RESTRICT,
    cantidad_solicitada  NUMERIC(14,4) NOT NULL,
    id_unidad            INTEGER       NOT NULL REFERENCES unidad_medida (id_unidad) ON DELETE RESTRICT,
    precio_pactado       NUMERIC(12,4) NOT NULL,
    CONSTRAINT uq_ocd UNIQUE (id_orden_compra, id_item),
    CONSTRAINT uq_ocd_id_orden UNIQUE (id_oc_detalle, id_orden_compra),  -- [N8] Destino de FK compuesta
    CONSTRAINT chk_ocd_cantidad CHECK (cantidad_solicitada > 0),
    CONSTRAINT chk_ocd_precio CHECK (precio_pactado >= 0)
);

CREATE INDEX idx_ocd_item ON orden_compra_detalle (id_item);
CREATE INDEX idx_ocd_unidad ON orden_compra_detalle (id_unidad);

CREATE TABLE recepcion (
    id_recepcion     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden_compra  INTEGER     NOT NULL REFERENCES orden_compra (id_orden_compra) ON DELETE RESTRICT,
    fecha_recepcion  TIMESTAMP   NOT NULL DEFAULT now(),
    estado           VARCHAR(15) NOT NULL DEFAULT 'completa',
    observaciones    TEXT,
    CONSTRAINT uq_recepcion_id_orden UNIQUE (id_recepcion, id_orden_compra)  -- [N8] Destino de FK compuesta
);

CREATE INDEX idx_recepcion_orden ON recepcion (id_orden_compra);

CREATE TABLE recepcion_detalle (
    id_recepcion_detalle  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_recepcion          INTEGER       NOT NULL,
    id_orden_compra       INTEGER       NOT NULL,  -- [N8] Obliga a recibir líneas de la misma orden
    id_oc_detalle         INTEGER       NOT NULL,
    cantidad_recibida     NUMERIC(14,4) NOT NULL,
    id_unidad             INTEGER       NOT NULL REFERENCES unidad_medida (id_unidad) ON DELETE RESTRICT,
    costo_real_unitario   NUMERIC(12,4) NOT NULL,
    CONSTRAINT fk_recepcion_detalle_recepcion FOREIGN KEY (id_recepcion, id_orden_compra)
        REFERENCES recepcion (id_recepcion, id_orden_compra) ON DELETE CASCADE,
    CONSTRAINT fk_recepcion_detalle_ocd FOREIGN KEY (id_oc_detalle, id_orden_compra)
        REFERENCES orden_compra_detalle (id_oc_detalle, id_orden_compra) ON DELETE RESTRICT,
    CONSTRAINT chk_recepcion_cantidad CHECK (cantidad_recibida > 0),
    CONSTRAINT chk_recepcion_costo CHECK (costo_real_unitario >= 0)
);

CREATE INDEX idx_recepcion_detalle_recepcion ON recepcion_detalle (id_recepcion, id_orden_compra);
CREATE INDEX idx_recepcion_detalle_ocd ON recepcion_detalle (id_oc_detalle, id_orden_compra);
CREATE INDEX idx_recepcion_detalle_unidad ON recepcion_detalle (id_unidad);

-- =====================================================================
-- 4. Reservas y pedidos
-- =====================================================================

CREATE TABLE reserva (
    id_reserva           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente           INTEGER     NOT NULL REFERENCES cliente (id_cliente) ON DELETE RESTRICT,
    id_mesa              INTEGER     NOT NULL REFERENCES mesa (id_mesa) ON DELETE RESTRICT,
    fecha                DATE        NOT NULL,
    hora                 TIME        NOT NULL,
    cantidad_comensales  INTEGER     NOT NULL,
    estado               VARCHAR(15) NOT NULL DEFAULT 'pendiente',
    observaciones        TEXT,
    CONSTRAINT chk_reserva_comensales CHECK (cantidad_comensales > 0)
);

CREATE INDEX idx_reserva_cliente ON reserva (id_cliente);
CREATE INDEX idx_reserva_mesa_fecha ON reserva (id_mesa, fecha);

CREATE TABLE reserva_detalle (
    id_reserva_detalle  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva          INTEGER       NOT NULL REFERENCES reserva (id_reserva) ON DELETE CASCADE,
    id_item             INTEGER       NOT NULL REFERENCES item (id_item) ON DELETE RESTRICT,
    cantidad            NUMERIC(14,4) NOT NULL,
    observaciones       TEXT,
    CONSTRAINT uq_reserva_detalle UNIQUE (id_reserva, id_item),
    CONSTRAINT chk_reserva_detalle_cantidad CHECK (cantidad > 0)
);

CREATE INDEX idx_reserva_detalle_item ON reserva_detalle (id_item);

CREATE TABLE pedido (
    id_pedido      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva     INTEGER     REFERENCES reserva (id_reserva) ON DELETE RESTRICT,
    fecha_hora     TIMESTAMP   NOT NULL DEFAULT now(),
    estado         VARCHAR(15) NOT NULL DEFAULT 'abierto',
    observaciones  TEXT
);

CREATE INDEX idx_pedido_reserva ON pedido (id_reserva);

CREATE TABLE pedido_detalle (
    id_pedido_detalle  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido          INTEGER       NOT NULL REFERENCES pedido (id_pedido) ON DELETE CASCADE,
    id_presentacion    INTEGER       NOT NULL REFERENCES item_presentacion (id_presentacion) ON DELETE RESTRICT,
    cantidad           NUMERIC(14,4) NOT NULL,
    precio_unitario    NUMERIC(12,2) NOT NULL,  -- Copia del precio al momento del pedido
    origen             VARCHAR(15)   NOT NULL,
    CONSTRAINT chk_pedido_detalle_cantidad CHECK (cantidad > 0),
    CONSTRAINT chk_pedido_detalle_precio CHECK (precio_unitario >= 0)
);

CREATE INDEX idx_pedido_detalle_pedido ON pedido_detalle (id_pedido);
CREATE INDEX idx_pedido_detalle_presentacion ON pedido_detalle (id_presentacion);

-- =====================================================================
-- 5. Producción
-- =====================================================================

CREATE TABLE orden_produccion (
    id_orden_produccion  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_receta            INTEGER       NOT NULL REFERENCES receta (id_receta) ON DELETE RESTRICT,
    -- [N7] Antes en pedido_detalle_orden; cada orden atiende como máximo una línea de pedido
    id_pedido_detalle    INTEGER       REFERENCES pedido_detalle (id_pedido_detalle) ON DELETE SET NULL,
    tipo                 VARCHAR(15)   NOT NULL,
    estado               VARCHAR(15)   NOT NULL DEFAULT 'planificada',
    fecha_planificada    TIMESTAMP,
    fecha_ejecucion      TIMESTAMP,
    rendimiento_real     NUMERIC(14,4),
    observaciones        TEXT,
    CONSTRAINT chk_op_rendimiento CHECK (rendimiento_real IS NULL OR rendimiento_real >= 0)
);

CREATE INDEX idx_op_receta ON orden_produccion (id_receta);
CREATE INDEX idx_op_pedido_detalle ON orden_produccion (id_pedido_detalle);

CREATE TABLE orden_produccion_detalle (
    id_op_detalle        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden_produccion  INTEGER       NOT NULL REFERENCES orden_produccion (id_orden_produccion) ON DELETE CASCADE,
    id_item_insumo       INTEGER       NOT NULL REFERENCES item (id_item) ON DELETE RESTRICT,
    cantidad_teorica     NUMERIC(14,4) NOT NULL,
    cantidad_real        NUMERIC(14,4),
    id_unidad            INTEGER       NOT NULL REFERENCES unidad_medida (id_unidad) ON DELETE RESTRICT,
    merma_asociada       NUMERIC(14,4) NOT NULL DEFAULT 0,
    CONSTRAINT uq_opd UNIQUE (id_orden_produccion, id_item_insumo),
    CONSTRAINT chk_opd_cantidades CHECK (
        cantidad_teorica > 0 AND (cantidad_real IS NULL OR cantidad_real >= 0) AND merma_asociada >= 0
    )
);

CREATE INDEX idx_opd_insumo ON orden_produccion_detalle (id_item_insumo);
CREATE INDEX idx_opd_unidad ON orden_produccion_detalle (id_unidad);

-- =====================================================================
-- 6. Inventario
-- =====================================================================

CREATE TABLE lote_inventario (
    id_lote               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_item               INTEGER       NOT NULL REFERENCES item (id_item) ON DELETE RESTRICT,
    codigo_lote           VARCHAR(60)   NOT NULL,
    -- [N5] Se eliminó "origen": se deduce de cuál de estas dos columnas tiene valor
    -- (ninguna = stock inicial o ajuste)
    id_recepcion_detalle  INTEGER       REFERENCES recepcion_detalle (id_recepcion_detalle) ON DELETE RESTRICT,
    id_orden_produccion   INTEGER       REFERENCES orden_produccion (id_orden_produccion) ON DELETE RESTRICT,
    fecha_ingreso         TIMESTAMP     NOT NULL DEFAULT now(),
    fecha_vencimiento     DATE,
    cantidad_inicial      NUMERIC(14,4) NOT NULL,
    costo_unitario        NUMERIC(12,4) NOT NULL,
    id_unidad             INTEGER       NOT NULL REFERENCES unidad_medida (id_unidad) ON DELETE RESTRICT,
    estado                VARCHAR(15)   NOT NULL DEFAULT 'disponible',
    CONSTRAINT uq_lote UNIQUE (id_item, codigo_lote),
    CONSTRAINT uq_lote_id_item UNIQUE (id_lote, id_item),  -- [N8] Destino de FK compuesta
    CONSTRAINT chk_lote_un_origen CHECK (num_nonnulls(id_recepcion_detalle, id_orden_produccion) <= 1),
    CONSTRAINT chk_lote_cantidad CHECK (cantidad_inicial > 0),
    CONSTRAINT chk_lote_costo CHECK (costo_unitario >= 0),
    CONSTRAINT chk_lote_vencimiento CHECK (fecha_vencimiento IS NULL OR fecha_vencimiento >= fecha_ingreso::date)
);

CREATE INDEX idx_lote_recepcion_detalle ON lote_inventario (id_recepcion_detalle);
CREATE INDEX idx_lote_orden_produccion ON lote_inventario (id_orden_produccion);
CREATE INDEX idx_lote_unidad ON lote_inventario (id_unidad);
CREATE INDEX idx_lote_vencimiento ON lote_inventario (id_item, fecha_vencimiento) WHERE estado = 'disponible';

CREATE TABLE movimiento_inventario (
    id_movimiento         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_item               INTEGER       NOT NULL REFERENCES item (id_item) ON DELETE RESTRICT,
    id_tipo_movimiento    INTEGER       NOT NULL REFERENCES tipo_movimiento (id_tipo_movimiento) ON DELETE RESTRICT,
    id_lote               INTEGER,
    cantidad              NUMERIC(14,4) NOT NULL,  -- Siempre positiva; el signo lo da tipo_movimiento
    id_unidad             INTEGER       NOT NULL REFERENCES unidad_medida (id_unidad) ON DELETE RESTRICT,
    costo_unitario        NUMERIC(12,4) NOT NULL DEFAULT 0,
    -- [N4] Documento de origen, antes origen_tipo + origen_id sin integridad referencial.
    -- Ninguno = ajuste manual o merma (la merma apunta a este movimiento).
    id_recepcion_detalle  INTEGER       REFERENCES recepcion_detalle (id_recepcion_detalle) ON DELETE RESTRICT,
    id_op_detalle         INTEGER       REFERENCES orden_produccion_detalle (id_op_detalle) ON DELETE RESTRICT,
    id_orden_produccion   INTEGER       REFERENCES orden_produccion (id_orden_produccion) ON DELETE RESTRICT,
    id_pedido_detalle     INTEGER       REFERENCES pedido_detalle (id_pedido_detalle) ON DELETE RESTRICT,
    fecha_movimiento      TIMESTAMP     NOT NULL DEFAULT now(),
    id_usuario            INTEGER       REFERENCES usuario (id_usuario) ON DELETE RESTRICT,  -- [N6]
    observaciones         TEXT,
    -- [N8] Si se indica lote, debe ser un lote del mismo ítem
    CONSTRAINT fk_movimiento_lote_item FOREIGN KEY (id_lote, id_item)
        REFERENCES lote_inventario (id_lote, id_item) ON DELETE RESTRICT,
    CONSTRAINT chk_movimiento_un_origen CHECK (
        num_nonnulls(id_recepcion_detalle, id_op_detalle, id_orden_produccion, id_pedido_detalle) <= 1
    ),
    CONSTRAINT chk_movimiento_cantidad CHECK (cantidad > 0),
    CONSTRAINT chk_movimiento_costo CHECK (costo_unitario >= 0)
);

CREATE INDEX idx_mov_item_fecha ON movimiento_inventario (id_item, fecha_movimiento);
CREATE INDEX idx_mov_tipo ON movimiento_inventario (id_tipo_movimiento);
CREATE INDEX idx_mov_lote ON movimiento_inventario (id_lote, id_item);
CREATE INDEX idx_mov_unidad ON movimiento_inventario (id_unidad);
CREATE INDEX idx_mov_recepcion_detalle ON movimiento_inventario (id_recepcion_detalle);
CREATE INDEX idx_mov_op_detalle ON movimiento_inventario (id_op_detalle);
CREATE INDEX idx_mov_orden_produccion ON movimiento_inventario (id_orden_produccion);
CREATE INDEX idx_mov_pedido_detalle ON movimiento_inventario (id_pedido_detalle);
CREATE INDEX idx_mov_usuario ON movimiento_inventario (id_usuario);

CREATE TABLE merma (
    id_merma                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_movimiento           BIGINT      NOT NULL UNIQUE REFERENCES movimiento_inventario (id_movimiento) ON DELETE CASCADE,
    motivo                  VARCHAR(20) NOT NULL,
    id_usuario_responsable  INTEGER     REFERENCES usuario (id_usuario) ON DELETE RESTRICT,  -- [N6]
    descripcion             TEXT
);

CREATE INDEX idx_merma_usuario ON merma (id_usuario_responsable);

-- =====================================================================
-- 7. Ventas y pagos
-- =====================================================================

CREATE TABLE venta (
