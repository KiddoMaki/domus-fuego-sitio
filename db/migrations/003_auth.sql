-- Autenticación y roles para la parte de reservas.
-- Se aplica después de DomusDBs.sql y de 002_carta_fields.sql.

CREATE TABLE IF NOT EXISTS roles (
  id_rol      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      VARCHAR(30) NOT NULL UNIQUE,
  descripcion TEXT
);

CREATE TABLE IF NOT EXISTS usuarios (
  id_usuario    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        VARCHAR(120) NOT NULL,
  email         VARCHAR(160) NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  activo        BOOLEAN NOT NULL DEFAULT TRUE,
  id_cliente    INTEGER REFERENCES cliente (id_cliente) ON DELETE SET NULL,
  created_at    TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS rolesxusuario (
  id_rolxusuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario     INTEGER NOT NULL REFERENCES usuarios (id_usuario) ON DELETE CASCADE,
  id_rol         INTEGER NOT NULL REFERENCES roles (id_rol) ON DELETE CASCADE,
  CONSTRAINT uq_rolesxusuario UNIQUE (id_usuario, id_rol)
);

