-- Bitácora real de acciones del panel administrativo.
create table if not exists public.auditoria_log (
  id_auditoria_log bigint generated by default as identity primary key,
  fecha timestamp without time zone not null default now(),
  usuario character varying(120) not null,
  modulo character varying(80) not null,
  accion character varying(80) not null,
  detalle text,
  ip character varying(64)
);

create index if not exists idx_auditoria_log_fecha
  on public.auditoria_log (fecha desc, id_auditoria_log desc);
